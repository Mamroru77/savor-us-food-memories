const B64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';

// The mini program runtime has no btoa; SVG markup is ASCII, so a small encoder is enough.
function base64(input) {
  let out = '';
  for (let i = 0; i < input.length; i += 3) {
    const a = input.charCodeAt(i);
    const b = input.charCodeAt(i + 1);
    const c = input.charCodeAt(i + 2);
    const triple = (a << 16) | ((isNaN(b) ? 0 : b) << 8) | (isNaN(c) ? 0 : c);
    out += B64[(triple >> 18) & 63] + B64[(triple >> 12) & 63]
      + (isNaN(b) ? '=' : B64[(triple >> 6) & 63]) + (isNaN(c) ? '=' : B64[triple & 63]);
  }
  return out;
}

function svgDataUri(svg) { return 'data:image/svg+xml;base64,' + base64(svg); }

function iconSvg(name, options) {
  const body = icons[name];
  if (!body) return '';
  const o = options || {};
  const color = o.color || '#1b1c1a';
  const fill = o.fill === 'current' ? color : (o.fill || 'none');
  const alt = o.alt || (fill === 'none' ? color : '#f5f4f1');
  return svgDataUri('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="' + fill + '" stroke="' + color
    + '" stroke-width="' + (o.stroke || 1.5) + '" stroke-linecap="round" stroke-linejoin="round">' + body.replace(/__ALT__/g, alt) + '</svg>');
}

